from __future__ import annotations

import io
from pathlib import Path

import streamlit as st
import timm
import torch
from PIL import Image
from torchvision import transforms


APP_DIR = Path(__file__).resolve().parent
DEFAULT_CHECKPOINT = APP_DIR / "outputs" / "best.pt"
DEFAULT_MODEL_NAME = "vit_base_patch16_224"
DEFAULT_IMAGE_SIZE = 224


st.set_page_config(
    page_title="Vehicle Defect Classification",
    page_icon="🚗",
    layout="wide",
)

st.title("Vehicle Surface Defect Classification")
st.caption("Vision Transformer (ViT) image-classification demonstration")

with st.sidebar:
    st.header("Model settings")
    st.write("Select the trained checkpoint produced by the project training code.")
    uploaded_checkpoint = st.file_uploader(
        "Upload best.pt (optional if saved in outputs/)",
        type=["pt", "pth"],
        help="Use the best.pt checkpoint generated by src/train.py.",
    )

    if uploaded_checkpoint is not None:
        checkpoint_bytes = uploaded_checkpoint.getvalue()
        checkpoint_name = uploaded_checkpoint.name
    elif DEFAULT_CHECKPOINT.exists():
        checkpoint_bytes = DEFAULT_CHECKPOINT.read_bytes()
        checkpoint_name = str(DEFAULT_CHECKPOINT.relative_to(APP_DIR))
    else:
        checkpoint_bytes = None
        checkpoint_name = None

    st.caption(f"Checkpoint: {checkpoint_name or 'Not selected'}")

if checkpoint_bytes is None:
    st.warning("The trained model checkpoint is not included in the supplied CODE.rar archive.")
    st.markdown(
        """
        **Before running the demo:**
        1. Locate the trained `best.pt` file from your training run.
        2. Either upload it in the sidebar or copy it to `outputs/best.pt`.
        3. Restart or refresh this Streamlit page.
        """
    )
    st.stop()


@st.cache_resource(show_spinner="Loading the trained Vision Transformer model...")
def load_trained_model(raw_checkpoint: bytes):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    checkpoint = torch.load(io.BytesIO(raw_checkpoint), map_location=device, weights_only=False)

    if not isinstance(checkpoint, dict) or "model_state" not in checkpoint:
        raise ValueError(
            "This file does not look like a project checkpoint. "
            "Expected a dictionary containing 'model_state'."
        )

    saved_config = checkpoint.get("config") or {}
    model_name = saved_config.get("model_name", DEFAULT_MODEL_NAME)
    num_classes = int(saved_config.get("num_classes", 2))
    image_size = int(saved_config.get("image_size", DEFAULT_IMAGE_SIZE))

    # The trained checkpoint supplies the learned weights, so pretrained=False
    # avoids an unnecessary internet download of the original ImageNet weights.
    model = timm.create_model(
        model_name,
        pretrained=False,
        num_classes=num_classes,
    )
    model.load_state_dict(checkpoint["model_state"], strict=True)
    model.to(device)
    model.eval()

    class_to_idx = checkpoint.get("class_to_idx")
    if isinstance(class_to_idx, dict) and class_to_idx:
        idx_to_class = {int(index): str(name) for name, index in class_to_idx.items()}
    else:
        idx_to_class = {index: f"class_{index}" for index in range(num_classes)}

    preprocess = transforms.Compose(
        [
            transforms.Resize((image_size, image_size)),
            transforms.ToTensor(),
            transforms.Normalize(
                mean=[0.485, 0.456, 0.406],
                std=[0.229, 0.224, 0.225],
            ),
        ]
    )

    return model, device, preprocess, idx_to_class, model_name, image_size


try:
    model, device, preprocess, idx_to_class, model_name, image_size = load_trained_model(
        checkpoint_bytes
    )
except Exception as exc:
    st.error(f"Could not load the checkpoint: {exc}")
    st.info(
        "Confirm that you selected the `best.pt` file generated by this project's "
        "`src/train.py`, and that the matching `timm` model architecture is available."
    )
    st.stop()

col_a, col_b, col_c = st.columns(3)
col_a.metric("Model architecture", model_name)
col_b.metric("Input image size", f"{image_size} × {image_size}")
col_c.metric("Execution device", str(device).upper())

st.divider()
st.subheader("Upload an image for classification")
uploaded_image = st.file_uploader(
    "Choose a vehicle image",
    type=["jpg", "jpeg", "png", "bmp", "webp"],
)

if uploaded_image is not None:
    try:
        image = Image.open(uploaded_image).convert("RGB")
    except Exception as exc:
        st.error(f"Unable to read this image: {exc}")
        st.stop()

    left, right = st.columns([1, 1], gap="large")
    with left:
        st.markdown("#### Input image")
        st.image(image, use_container_width=True)
        st.caption(f"Original image dimensions: {image.width} × {image.height}")

    with right:
        st.markdown("#### Model prediction")
        if st.button("Run classification", type="primary", use_container_width=True):
            with st.spinner("Analysing image..."):
                input_tensor = preprocess(image).unsqueeze(0).to(device)
                with torch.inference_mode():
                    logits = model(input_tensor)
                    probabilities = torch.softmax(logits, dim=1)[0].detach().cpu()

                predicted_index = int(torch.argmax(probabilities).item())
                predicted_class = idx_to_class.get(
                    predicted_index, f"class_{predicted_index}"
                )
                confidence = float(probabilities[predicted_index].item()) * 100.0

                st.session_state["prediction_result"] = {
                    "class": predicted_class,
                    "confidence": confidence,
                    "probabilities": {
                        idx_to_class.get(i, f"class_{i}"): float(probabilities[i].item()) * 100.0
                        for i in range(len(probabilities))
                    },
                }

        result = st.session_state.get("prediction_result")
        if result:
            display_name = result["class"].replace("_", " ").title()
            st.success(f"Predicted class: {display_name}")
            st.metric("Prediction confidence", f'{result["confidence"]:.2f}%')
            st.markdown("**Class probabilities**")
            probability_data = {
                name.replace("_", " ").title(): value
                for name, value in result["probabilities"].items()
            }
            st.bar_chart(probability_data, horizontal=True)
            st.caption(
                "The displayed class names and class indices are read from the "
                "training checkpoint when available."
            )
        else:
            st.info("Select **Run classification** to generate a prediction.")

st.divider()
st.caption(
    "Demonstration interface for the trained project model. "
    "Predictions depend on the quality and suitability of the input image."
)
